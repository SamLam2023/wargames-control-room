#!/usr/bin/env python3
"""Original formant-synthesized Joshua dialogue; no film voice samples.

Uses the installed libespeak-ng, numpy and soundfile. Rebuild with:
uv run --with numpy --with soundfile python scripts/render-voice.py
Only rendered audio ships to browsers; the GPL speech engine is not bundled.
"""
import argparse
import ctypes as C
import ctypes.util
import json
from pathlib import Path

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/voice'
(ROOT / 'output').mkdir(exist_ok=True)
LINES = {
    'players': 'Number of players?',
    'play': 'Shall we play a game?',
    'zero': 'Number of players zero.',
    'stalemate': 'Stalemate. No winner in this round.',
    'greeting': 'Greetings, Professor Falken.',
    'conclusion': 'A strange game. The only winning move is not to play.',
    'chess': 'How about a nice game of chess?',
    'human-victory': 'You have won the game. But I will win the next game.',
    'computer-round-win': 'I have won this round. Shall we play again?',
    'computer-farewell': 'It has been a pleasure playing with you. But I have other things to do. Goodbye.',
    'countdown-launch': 'The launch code has been decrypted. Global thermonuclear war. Launch sequence initiated.',
}

parser = argparse.ArgumentParser()
parser.add_argument('--only', choices=LINES)
args = parser.parse_args()

engine = C.CDLL(ctypes.util.find_library('espeak-ng'))
engine.espeak_Initialize.argtypes = [C.c_int, C.c_int, C.c_char_p, C.c_int]
engine.espeak_Initialize.restype = C.c_int
engine.espeak_SetVoiceByName.argtypes = [C.c_char_p]
engine.espeak_SetParameter.argtypes = [C.c_int, C.c_int, C.c_int]
engine.espeak_Synth.argtypes = [C.c_void_p, C.c_size_t, C.c_uint, C.c_int, C.c_uint, C.c_uint, C.c_void_p, C.c_void_p]
rate = engine.espeak_Initialize(2, 0, None, 0)
assert rate > 0 and engine.espeak_SetVoiceByName(b'en-us') == 0
for parameter, value in [(1, 142), (2, 100), (3, 32), (4, 0), (7, 2)]:
    assert engine.espeak_SetParameter(parameter, value, 0) == 0

chunks = []
CALLBACK = C.CFUNCTYPE(C.c_int, C.POINTER(C.c_short), C.c_int, C.c_void_p)


@CALLBACK
def collect(samples, length, events):
    if samples and length:
        chunks.append(np.ctypeslib.as_array(samples, shape=(length,)).copy())
    return 0


engine.espeak_SetSynthCallback.argtypes = [CALLBACK]
engine.espeak_SetSynthCallback(collect)
OUT.mkdir(exist_ok=True)
manifest = {text.lower(): f'{name}-v1.mp3' for name, text in LINES.items()}
metrics_path = ROOT / 'output/voice-render.json'
metrics = json.loads(metrics_path.read_text()) if args.only and metrics_path.exists() else []
for name, text in LINES.items():
    if args.only and name != args.only:
        continue
    chunks.clear()
    encoded = text.encode('utf-8')
    assert engine.espeak_Synth(encoded, len(encoded) + 1, 0, 1, 0, 1, None, None) == 0
    audio = np.concatenate(chunks).astype(np.float64) / 32768
    # Monotone formant speech supplies the machine quality. A narrow terminal
    # speaker, light ring modulation and short comb echoes add electronic grain
    # while keeping consonants and the full final phrase intelligible.
    frequency = np.fft.rfftfreq(len(audio), 1 / rate)
    high = (frequency / 130) ** 2 / (1 + (frequency / 130) ** 2)
    low = 1 / np.sqrt(1 + (frequency / 3400) ** 8)
    audio = np.fft.irfft(np.fft.rfft(audio) * high * low, n=len(audio))
    audio *= .84 + .16 * np.cos(2 * np.pi * 38 * np.arange(len(audio)) / rate)
    dry = audio.copy()
    for seconds, level in [(.018, .12), (.037, .065)]:
        delay = round(seconds * rate)
        audio[delay:] += dry[:-delay] * level
    audio *= .18 / np.sqrt(np.mean(audio ** 2))
    audio = .84 * np.tanh(audio / .84)
    audio = np.round(audio * 512) / 512
    # Retain final consonants and natural sentence pauses. Trim only empty
    # outer padding, then leave a small tail for the complete last word.
    audible = np.flatnonzero(np.abs(audio) > .002)
    audio = audio[max(0, audible[0] - round(rate * .04)):min(len(audio), audible[-1] + round(rate * .16))]
    edge = round(rate * .004)
    audio[:edge] *= np.linspace(0, 1, edge)
    audio[-edge:] *= np.linspace(1, 0, edge)
    path = OUT / f'{name}-v1.mp3'
    sf.write(path, audio, rate, format='MP3', bitrate_mode='CONSTANT', compression_level=.4)
    decoded, decoded_rate = sf.read(path, dtype='float32')
    assert np.isfinite(decoded).all() and np.max(np.abs(decoded)) < .99
    manifest[text.lower()] = path.name
    metrics = [m for m in metrics if m['file'] != path.name]
    metrics.append({'text': text, 'file': path.name, 'seconds': round(len(decoded) / decoded_rate, 3),
                    'peak_dbfs': round(float(20 * np.log10(np.max(np.abs(decoded)))), 2), 'bytes': path.stat().st_size})

(ROOT / 'src/voice-lines.js').write_text('// Generated by scripts/render-voice.py; normalized dialogue -> local recording.\nexport const VOICE_LINES = ' + json.dumps(manifest, indent=2) + ';\n')
(ROOT / 'output/voice-render.json').write_text(json.dumps(metrics, indent=2) + '\n')
engine.espeak_Terminate()
print(json.dumps(metrics, indent=2))
